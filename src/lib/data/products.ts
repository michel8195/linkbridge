// Helper to get products by niche
export function getProductsByNiche(niche: string): ProductSeed[] {
  return PRODUCT_CATALOG.filter((p) =>
    p.niche.some((n) => n.toLowerCase() === niche.toLowerCase())
  );
}

// Helper to get niche stats
export function getNicheStats(): Record<string, { count: number; avgCommission: number }> {
  const stats: Record<string, { count: number; totalCommission: number }> = {};

  for (const product of PRODUCT_CATALOG) {
    for (const niche of product.niche) {
      if (!stats[niche]) stats[niche] = { count: 0, totalCommission: 0 };
      stats[niche].count++;
      stats[niche].totalCommission += product.commissionRate;
    }
  }

  const result: Record<string, { count: number; avgCommission: number }> = {};
  for (const [niche, data] of Object.entries(stats)) {
    result[niche] = {
      count: data.count,
      avgCommission: Math.round((data.totalCommission / data.count) * 10) / 10,
    };
  }
  return result;
}
